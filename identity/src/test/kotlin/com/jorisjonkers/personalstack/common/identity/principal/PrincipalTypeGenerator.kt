package com.jorisjonkers.personalstack.common.identity.principal

import com.fasterxml.jackson.databind.JsonNode
import com.fasterxml.jackson.databind.ObjectMapper

/**
 * Writes the Kotlin type of identity's Principal contract from its JSON Schema, so a field the
 * contract adds reaches the adapter mechanically. It knows the shapes the schema uses: strings
 * (with an enum or as a date-time), booleans, arrays of strings, and objects of those.
 */
object PrincipalTypeGenerator {
    fun generate(
        pkg: String,
        schema: String,
    ): String {
        val root = ObjectMapper().readTree(schema)
        val types = mutableListOf<String>()
        types += dataClass(root.path("title").asText(), root, types)
        return buildString {
            append("// Generated by PrincipalTypeGenerator from the Principal contract's schema; do not edit.\n")
            append("package $pkg\n\n")
            append("import java.time.Instant\n")
            types.reversed().forEach { append("\n").append(it) }
        }
    }

    private fun dataClass(
        name: String,
        schema: JsonNode,
        types: MutableList<String>,
    ): String {
        val required = schema.path("required").map { it.asText() }.toSet()
        val fields =
            schema.path("properties").properties().map { (property, field) ->
                val optional = property !in required
                val type = typeOf(property, field, types)
                "${docOf(field, "    ")}    val $property: $type${if (optional) "? = null" else ""},\n"
            }
        return "${docOf(schema)}data class $name(\n${fields.joinToString("")})\n"
    }

    private fun typeOf(
        property: String,
        field: JsonNode,
        types: MutableList<String>,
    ): String {
        val type = field.path("type").asText()
        return when {
            field.has("enum") -> enumClass(property.replaceFirstChar { it.uppercase() }, field, types)
            type == "string" && field.path("format").asText() == "date-time" -> "Instant"
            type == "string" -> "String"
            type == "boolean" -> "Boolean"
            type == "array" && field.path("items").path("type").asText() == "string" -> "List<String>"
            type == "object" -> {
                val name = property.replaceFirstChar { it.uppercase() }
                types += dataClass(name, field, types)
                name
            }
            else -> throw IllegalArgumentException("no Kotlin type for $property (type \"$type\")")
        }
    }

    private fun enumClass(
        name: String,
        field: JsonNode,
        types: MutableList<String>,
    ): String {
        val values =
            field.path("enum").map { it.asText() }.sorted().joinToString("") {
                "    ${it.uppercase().replace('-', '_')}(\"$it\"),\n"
            }
        types += "${docOf(field)}enum class $name(\n    val value: String,\n) {\n$values}\n"
        return name
    }

    private fun docOf(
        node: JsonNode,
        indent: String = "",
    ): String {
        val description = node.path("description").asText()
        val single = "$indent/** $description */"
        return when {
            description.isEmpty() -> ""
            single.length <= MAX_LINE -> "$single\n"
            else ->
                wrap(description, MAX_LINE - indent.length - 3).joinToString(
                    separator = "",
                    prefix = "$indent/**\n",
                    postfix = "$indent */\n",
                ) { "$indent * $it\n" }
        }
    }

    private fun wrap(
        text: String,
        width: Int,
    ): List<String> =
        text.split(" ").fold(mutableListOf("")) { lines, word ->
            val last = lines.last()
            when {
                last.isEmpty() -> lines[lines.lastIndex] = word
                last.length + 1 + word.length > width -> lines += word
                else -> lines[lines.lastIndex] = "$last $word"
            }
            lines
        }

    private const val MAX_LINE = 120
}
